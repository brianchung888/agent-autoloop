# -- Constants ---------------------------------------------------------

# Flag hardcoded by the daemon that user custom_args must not override:
# the daemon owns the stdio:// transport used to talk to the app-server.
CODEX_BLOCKED_ARGS: Dict[str, BlockedArgMode] = {
    "--listen": BlockedArgMode.BLOCKED_WITH_VALUE,
}

CODEX_STDERR_TAIL_BYTES = 2048
DEFAULT_CODEX_SEMANTIC_INACTIVITY_TIMEOUT = 10 * 60.0     # 10 minutes
DEFAULT_CODEX_FIRST_TURN_NO_PROGRESS_TIMEOUT = 30.0
CODEX_VERSION_DIAGNOSTIC_TIMEOUT = 2.0
CODEX_GRACEFUL_SHUTDOWN_TIMEOUT = 10.0

# Prefix on timeout errors emitted when codex stops making semantic progress
# while its process is still alive.
CODEX_SEMANTIC_INACTIVITY_MARKER = "codex semantic inactivity timeout"
# The app-server failure mode where codex accepts a turn then never emits any
# item, completion or error.
CODEX_FIRST_TURN_NO_PROGRESS_MARKER = "codex app-server no progress timeout"
CODEX_MODEL_CATALOG_REFRESH_TIMEOUT_SIGNAL = (
    "failed to refresh available models: timeout waiting for child process to exit"
)

_ERR_CODEX_PROCESS_EXITED = "codex process exited"

# Timeout diagnostic kinds.
_TIMEOUT_NONE = 0
_TIMEOUT_SEMANTIC_INACTIVITY = 1
_TIMEOUT_FIRST_TURN_NO_PROGRESS = 2

# Matches the daemon-managed config namespace (`mcp_servers.…`) when it appears
# as the value of a Codex `-c` / `--config` flag.
_CODEX_MANAGED_MCP_CONFIG_KEY_RE = re.compile(r"^\s*mcp_servers(?:\s*\.|\s*=|\s*$)")

# Markers delimiting the daemon-managed `[mcp_servers.*]` block in config.toml.
_AGENTRUNNER_CODEX_MCP_BEGIN_MARKER = (
    "# BEGIN agentrunner-managed mcp_servers (do not edit; regenerated by daemon)"
)
_AGENTRUNNER_CODEX_MCP_END_MARKER = "# END agentrunner-managed mcp_servers"

_CODEX_MCP_BLOCK_RE = re.compile(
    r"(?ms)^" + re.escape(_AGENTRUNNER_CODEX_MCP_BEGIN_MARKER)
    + r".*?^" + re.escape(_AGENTRUNNER_CODEX_MCP_END_MARKER) + r"\n*"
)

# Matches `[mcp_servers.<name>]` (and its quoted-key form) at line start.
_USER_CODEX_MCP_SERVERS_TABLE_HEADER_RE = re.compile(
    r'^\s*\[\s*mcp_servers\s*\.\s*(?:"[^"]*"|[^\]\s]+)\s*\]\s*(?:#.*)?$'
)


# -- Argument / config-override building -------------------------------


def has_managed_codex_mcp_config(raw: Optional[bytes]) -> bool:
    """True when mcp_config is "present" (a non-null JSON value).

    Both ``{}`` and ``{"mcpServers":{}}`` count as present (admin saved an
    empty managed set — strict mode); only absent/``null`` count as absent.
    """
    if not raw:
        return False
    trimmed = raw.strip()
    if not trimmed or trimmed == b"null":
        return False
    return True


def filter_codex_custom_config_overrides(args: List[str], logger: Logger) -> List[str]:
    """Drop ``-c mcp_servers.…`` / ``--config mcp_servers.…`` overrides.

    Codex's ``-c`` is last-wins, so a user override would otherwise shadow the
    managed set the daemon wrote into ``$CODEX_HOME/config.toml``. Other
    ``-c`` keys (e.g. ``-c model="o3"``) pass through unchanged.
    """
    if not args:
        return args
    filtered: List[str] = []
    i = 0
    n = len(args)
    while i < n:
        arg = args[i]
        flag = arg
        inline_value = ""
        has_inline_value = False
        idx = arg.find("=")
        if idx > 0:
            flag = arg[:idx]
            inline_value = arg[idx + 1:]
            has_inline_value = True
        if flag in ("-c", "--config"):
            value = inline_value
            if not has_inline_value and i + 1 < n:
                value = args[i + 1]
            if _CODEX_MANAGED_MCP_CONFIG_KEY_RE.search(value):
                # Log the key only, never the value (env may carry secrets).
                key = value
                eq_idx = value.find("=")
                if eq_idx >= 0:
                    key = value[:eq_idx]
                logger.warn(
                    "custom_args: blocked mcp_servers override; daemon manages "
                    "this via CODEX_HOME/config.toml",
                    flag=flag, key=key.strip())
                if not has_inline_value and i + 1 < n:
                    i += 1  # skip the value arg
                i += 1
                continue
        filtered.append(arg)
        i += 1
    return filtered


def build_codex_args(opts: ExecOptions, logger: Logger) -> List[str]:
    """Build the argv (after the executable) for ``codex app-server``."""
    args = ["app-server", "--listen", "stdio://"]
    extra = filter_custom_args(opts.extra_args, CODEX_BLOCKED_ARGS, logger)
    custom = filter_custom_args(opts.custom_args, CODEX_BLOCKED_ARGS, logger)
    # Only claim ownership of the `mcp_servers` namespace when the agent has a
    # managed mcp_config; otherwise pre-existing `-c mcp_servers.…` custom_args
    # would silently vanish.
    if has_managed_codex_mcp_config(opts.mcp_config):
        extra = filter_codex_custom_config_overrides(extra, logger)
        custom = filter_codex_custom_config_overrides(custom, logger)
    args += extra
    args += custom
    return args


# -- Managed MCP config.toml materialisation ---------------------------
#
# mcp_servers.<id>.env may carry secrets, so we write the managed set to the
# per-task $CODEX_HOME/config.toml at mode 0600 rather than passing it via argv
# (which shows up in `ps` and the "agent command" log line).


def _is_multica_mcp_selector_key(k: str) -> bool:
    return k in ("tools", "prompts", "resources")


def _is_codex_remote_mcp_server(server: Dict[str, Any]) -> bool:
    typ = server.get("type")
    if isinstance(typ, str) and typ.lower() == "http":
        return True
    return "url" in server and "command" not in server


def _normalize_codex_mcp_server_config(server: Dict[str, Any]) -> Dict[str, Any]:
    if not _is_codex_remote_mcp_server(server):
        return {k: v for k, v in server.items()
                if not _is_multica_mcp_selector_key(k)}
    normalized: Dict[str, Any] = {}
    for k, v in server.items():
        if _is_multica_mcp_selector_key(k) or k == "type":
            continue
        if k == "headers":
            if "http_headers" not in server:
                normalized["http_headers"] = v
        else:
            normalized[k] = v
    normalized["experimental_use_rmcp_client"] = True
    return normalized


def _is_codex_bare_toml_key(s: str) -> bool:
    if not s:
        return False
    for r in s:
        if not (("a" <= r <= "z") or ("A" <= r <= "Z")
                or ("0" <= r <= "9") or r in ("_", "-")):
            return False
    return True


def _codex_toml_basic_string(s: str) -> str:
    out = ['"']
    escapes = {"\\": "\\\\", '"': '\\"', "\b": "\\b", "\t": "\\t",
               "\n": "\\n", "\f": "\\f", "\r": "\\r"}
    for ch in s:
        if ch in escapes:
            out.append(escapes[ch])
        elif ord(ch) < 0x20 or ord(ch) == 0x7f:
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def _codex_toml_key(s: str) -> str:
    return s if _is_codex_bare_toml_key(s) else _codex_toml_basic_string(s)


def _json_value_to_codex_toml_inline(v: Any) -> str:
    if v is None:
        raise ValueError("null is not a valid TOML value")
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if v == int(v):
            return str(int(v))
        return repr(v)
    if isinstance(v, str):
        return _codex_toml_basic_string(v)
    if isinstance(v, list):
        return "[" + ", ".join(_json_value_to_codex_toml_inline(e) for e in v) + "]"
    if isinstance(v, dict):
        parts = []
        for k in sorted(v.keys()):
            parts.append(_codex_toml_key(k) + " = "
                         + _json_value_to_codex_toml_inline(v[k]))
        return "{ " + ", ".join(parts) + " }"
    raise ValueError("unsupported value type %s" % type(v).__name__)


def render_codex_mcp_servers_block(raw: Optional[bytes]) -> Tuple[str, bool]:
    """Render mcp_config JSON as a TOML `[mcp_servers.<name>]` block.

    Returns ``(block, has_servers)``. ``has_servers=False`` means the input had
    no servers (caller only strips the prior managed block).
    """
    if not raw:
        return "", False
    parsed = json.loads(raw)
    servers = (parsed or {}).get("mcpServers") or {}
    if not servers:
        return "", False
    lines = [_AGENTRUNNER_CODEX_MCP_BEGIN_MARKER]
    for i, name in enumerate(sorted(servers.keys())):
        if not _is_codex_bare_toml_key(name):
            raise ValueError(
                "mcp server name %r must be ASCII alphanumeric / _ / - to fit "
                "Codex's bare-key requirement" % name)
        server_val = servers[name]
        if not isinstance(server_val, dict):
            raise ValueError("mcp_servers.%s must be a JSON object" % name)
        server_val = _normalize_codex_mcp_server_config(server_val)
        if i > 0:
            lines.append("")
        lines.append("[mcp_servers.%s]" % name)
        for k in sorted(server_val.keys()):
            try:
                toml_value = _json_value_to_codex_toml_inline(server_val[k])
            except ValueError as exc:
                raise ValueError("mcp_servers.%s.%s: %s" % (name, k, exc))
            lines.append("%s = %s" % (_codex_toml_key(k), toml_value))
    lines.append(_AGENTRUNNER_CODEX_MCP_END_MARKER)
    return "\n".join(lines) + "\n", True


def _strip_codex_user_mcp_server_tables(content: str) -> str:
    """Remove every `[mcp_servers.*]` table (header + body) from TOML text."""
    lines = content.split("\n")
    out: List[str] = []
    skipping = False
    for line in lines:
        if _USER_CODEX_MCP_SERVERS_TABLE_HEADER_RE.match(line):
            skipping = True
            continue
        if skipping:
            trimmed = line.strip()
            if trimmed.startswith("["):
                if (_USER_CODEX_MCP_SERVERS_TABLE_HEADER_RE.match(line)
                        or trimmed.startswith("[mcp_servers.")
                        or trimmed.startswith("[ mcp_servers.")):
                    continue
                skipping = False
                out.append(line)
                continue
            continue
        out.append(line)
    return "\n".join(out)


def ensure_codex_mcp_config(config_path: str, mcp_config: Optional[bytes],
                            logger: Logger) -> None:
    """Write (or clear) the daemon-managed `[mcp_servers.*]` block in config.toml."""
    existing = ""
    if os.path.exists(config_path):
        with open(config_path, "r", encoding="utf-8") as f:
            existing = f.read()

    # Always strip a prior managed block so reruns converge on a clean state.
    stripped = _CODEX_MCP_BLOCK_RE.sub("", existing)

    managed = has_managed_codex_mcp_config(mcp_config)
    block, _ = render_codex_mcp_servers_block(mcp_config)

    if managed:
        # Strict mode: strip inherited user `[mcp_servers.*]` tables so the
        # managed set is authoritative (mirrors Claude's --strict-mcp-config).
        stripped = _strip_codex_user_mcp_server_tables(stripped)
        stripped = stripped.rstrip("\n")
        if block == "":
            # Pin "managed but empty" on disk with an empty marker block.
            block = (_AGENTRUNNER_CODEX_MCP_BEGIN_MARKER + "\n"
                     + _AGENTRUNNER_CODEX_MCP_END_MARKER + "\n")
        updated = block if stripped == "" else stripped + "\n\n" + block
    else:
        updated = stripped

    if updated == existing:
        return
    with open(config_path, "w", encoding="utf-8") as f:
        f.write(updated)
    try:
        os.chmod(config_path, 0o600)  # keep secret-bearing values 0600
    except Exception:
        pass
    logger.debug("codex: wrote managed mcp_servers block to config.toml",
                 config_path=config_path, managed=managed)


# -- Reasoning-effort / small helpers ----------------------------------


def apply_codex_reasoning_effort(params: Dict[str, Any], level: str) -> None:
    """Inject the per-agent thinking_level into a codex app-server request.

    turn/start carries `input` and exposes the override as top-level `effort`;
    thread/start and thread/resume nest it under
    `config.model_reasoning_effort`. Empty level is a deliberate no-op.
    """
    if params is None or not level:
        return
    if "input" in params:
        params["effort"] = level
        return
    cfg = params.get("config")
    if not isinstance(cfg, dict):
        cfg = {}
    cfg["model_reasoning_effort"] = level
    params["config"] = cfg


def _nil_if_empty(s: str) -> Any:
    return s if s else None


def codex_first_turn_no_progress_timeout(semantic_inactivity_timeout: float) -> float:
    if (semantic_inactivity_timeout <= 0
            or semantic_inactivity_timeout > DEFAULT_CODEX_FIRST_TURN_NO_PROGRESS_TIMEOUT):
        return DEFAULT_CODEX_FIRST_TURN_NO_PROGRESS_TIMEOUT
    scaled = semantic_inactivity_timeout * 4 / 5
    return scaled if scaled > 0 else semantic_inactivity_timeout


def is_codex_first_turn_progress_activity(activity: str) -> bool:
    return activity not in ("", "status:running", "error:retry")


def describe_codex_semantic_activity(msg: Message) -> str:
    if msg.type in (MessageType.TOOL_USE, MessageType.TOOL_RESULT):
        if msg.tool:
            return "%s:%s" % (msg.type.value, msg.tool)
    elif msg.type == MessageType.STATUS:
        if msg.status:
            return "%s:%s" % (msg.type.value, msg.status)
    return msg.type.value


def _describe_codex_item_progress_activity(method: str, item_type: str,
                                           item_id: str) -> str:
    if not item_type:
        item_type = "unknown"
    if not item_id:
        return "%s:%s" % (method, item_type)
    return "%s:%s:%s" % (method, item_type, item_id)


def extract_thread_id(result: Any) -> str:
    if not isinstance(result, dict):
        return ""
    thread = result.get("thread")
    if isinstance(thread, dict):
        tid = thread.get("id")
        if isinstance(tid, str):
            return tid
    return ""


def extract_nested_string(m: Any, *keys: str) -> str:
    current: Any = m
    for key in keys:
        if not isinstance(current, dict):
            return ""
        current = current.get(key)
    return current if isinstance(current, str) else ""


def _codex_int64(m: Dict[str, Any], *keys: str) -> int:
    for key in keys:
        v = m.get(key)
        if isinstance(v, bool):
            continue
        if isinstance(v, (int, float)) and v != 0:
            return int(v)
    return 0


def _codex_uncached_input_tokens(input_tokens: int, cached_input_tokens: int) -> int:
    uncached = input_tokens - cached_input_tokens
    return uncached if uncached > 0 else 0


# -- Timeout diagnostics -----------------------------------------------


class _TimeoutDiagnostic:
    def __init__(self) -> None:
        self.kind = _TIMEOUT_NONE
        self.timeout = 0.0
        self.last_activity = ""
        self.thread_id = ""
        self.turn_id = ""
        self.model = ""
        self.codex_version = ""


def _non_empty_diag(value: str) -> str:
    return value if value and value.strip() else "unknown"


def _format_diag_model(model: str) -> str:
    return model if model and model.strip() else "default(empty)"


def _format_codex_diagnostic_fields(diag: _TimeoutDiagnostic) -> str:
    return 'codex_version=%r thread_id=%r turn_id=%r model=%r' % (
        _non_empty_diag(diag.codex_version),
        _non_empty_diag(diag.thread_id),
        _non_empty_diag(diag.turn_id),
        _format_diag_model(diag.model),
    )


def _append_codex_known_stderr_hint(msg: str, stderr_tail: str) -> str:
    if CODEX_MODEL_CATALOG_REFRESH_TIMEOUT_SIGNAL in stderr_tail:
        return (msg + "; diagnosis: Codex stderr shows the model catalog refresh "
                "timed out. Try setting an explicit model, switching Codex CLI "
                "versions, or using another runtime while Codex app-server recovers")
    return msg


def build_codex_timeout_diagnostic_error(diag: _TimeoutDiagnostic,
                                         stderr_tail: str) -> str:
    if diag.kind == _TIMEOUT_FIRST_TURN_NO_PROGRESS:
        msg = ("%s after %ss: received turn start but no item, message, tool, "
               "turn/completed, or error event (%s)" % (
                   CODEX_FIRST_TURN_NO_PROGRESS_MARKER, diag.timeout,
                   _format_codex_diagnostic_fields(diag)))
    elif diag.kind == _TIMEOUT_SEMANTIC_INACTIVITY:
        msg = ("%s after %ss without agent progress (last activity: %s; %s)" % (
            CODEX_SEMANTIC_INACTIVITY_MARKER, diag.timeout,
            _non_empty_diag(diag.last_activity),
            _format_codex_diagnostic_fields(diag)))
    else:
        msg = "codex timed out"
    msg = _append_codex_known_stderr_hint(msg, stderr_tail)
    return with_agent_stderr(msg, "codex", stderr_tail)


def detect_codex_version_for_diagnostics(exec_path: str, env: Dict[str, str],
                                         logger: Logger) -> str:
    try:
        proc = subprocess.run(
            [exec_path, "--version"], stdout=subprocess.PIPE,
            stderr=subprocess.PIPE, env=env,
            timeout=CODEX_VERSION_DIAGNOSTIC_TIMEOUT,
            **popen_platform_kwargs())
    except Exception as exc:  # noqa: BLE001
        logger.debug("codex version diagnostic failed", error=str(exc))
        return "unknown"
    version = extract_version_line(proc.stdout.decode("utf-8", "replace"))
    return version if version.strip() else "unknown"


# -- JSON-RPC 2.0 client ------------------------------------------------


class _PendingRPC:
    __slots__ = ("q", "method")

    def __init__(self, method: str) -> None:
        import queue as _queue
        self.q: "_queue.Queue[Tuple[Any, Optional[str]]]" = _queue.Queue(maxsize=1)
        self.method = method


class CodexClient:
    """JSON-RPC 2.0 transport over the app-server's stdin/stdout.

    ``request`` writes a request and blocks until the reader thread routes the
    matching response (or the process exits). Notifications and server-issued
    requests are dispatched by the reader thread; the client invokes the
    ``on_message`` / ``on_semantic_activity`` / ``on_turn_done`` callbacks.
    """

    def __init__(self, cfg: Config, stdin: Any,
                 on_message: Callable[[Message], None],
                 on_semantic_activity: Callable[[str], None],
                 on_turn_done: Callable[[bool], None],
                 opts: Optional[ExecOptions] = None) -> None:
        self.cfg = cfg
        self.opts = opts if opts is not None else ExecOptions()
        self._stdin = stdin
        self._stdin_lock = threading.Lock()
        self._lock = threading.Lock()
        self._next_id = 0
        self._pending: Dict[int, _PendingRPC] = {}
        self._process_err: Optional[str] = None
        self.process_done = threading.Event()

        self.thread_id = ""
        self.turn_id = ""
        self.on_message = on_message
        self.on_semantic_activity = on_semantic_activity
        self.on_turn_done = on_turn_done

        # "unknown" | "legacy" | "raw"
        self.notification_protocol = "unknown"
        self.turn_started = False
        self._completed_turn_ids: Dict[str, bool] = {}

        self._usage_lock = threading.Lock()
        self.usage = TokenUsage()

        self._turn_error_lock = threading.Lock()
        self._turn_error = ""

    # -- turn error --

    def set_turn_error(self, msg: str) -> None:
        if not msg:
            return
        with self._turn_error_lock:
            if not self._turn_error:
                self._turn_error = msg

    def get_turn_error(self) -> str:
        with self._turn_error_lock:
            return self._turn_error

    # -- low-level write --

    def _write(self, obj: Dict[str, Any]) -> None:
        data = (json.dumps(obj) + "\n").encode("utf-8")
        with self._stdin_lock:
            self._stdin.write(data)
            self._stdin.flush()

    # -- request / notify / respond --

    def request(self, method: str, params: Any) -> Tuple[Any, Optional[str]]:
        with self._lock:
            if self._process_err is not None:
                return None, self._process_err
            self._next_id += 1
            rpc_id = self._next_id
            pr = _PendingRPC(method)
            self._pending[rpc_id] = pr
        try:
            self._write({"jsonrpc": "2.0", "id": rpc_id,
                         "method": method, "params": params})
        except Exception as exc:  # noqa: BLE001
            with self._lock:
                self._pending.pop(rpc_id, None)
            return None, "write %s: %s" % (method, exc)
        if method == "turn/start":
            thread_id = ""
            if isinstance(params, dict):
                thread_id = params.get("threadId", "") or ""
            self.cfg.logger.info("codex turn/start sent",
                                 request_id=rpc_id, thread_id=thread_id)
        # Blocks until handle_response or mark_process_exited fills the queue.
        result, err = pr.q.get()
        return result, err

    def notify(self, method: str) -> None:
        try:
            self._write({"jsonrpc": "2.0", "method": method})
        except Exception:
            pass

    def respond(self, rpc_id: int, result: Any) -> None:
        try:
            self._write({"jsonrpc": "2.0", "id": rpc_id, "result": result})
        except Exception:
            pass

    def respond_error(self, rpc_id: int, code: int, message: str) -> None:
        try:
            self._write({"jsonrpc": "2.0", "id": rpc_id,
                         "error": {"code": code, "message": message}})
        except Exception:
            pass

    def mark_process_exited(self, err: Optional[str]) -> None:
        if not err:
            err = _ERR_CODEX_PROCESS_EXITED
        with self._lock:
            if self._process_err is None:
                self._process_err = err
                self.process_done.set()
            pending = list(self._pending.items())
            self._pending.clear()
        for _rpc_id, pr in pending:
            try:
                pr.q.put_nowait((None, err))
            except Exception:
                pass

    def get_process_err(self) -> Optional[str]:
        with self._lock:
            return self._process_err

    # -- line dispatch --

    def handle_line(self, line: str) -> None:
        try:
            raw = json.loads(line)
        except Exception:
            return
        if not isinstance(raw, dict):
            return
        has_id = "id" in raw
        has_method = "method" in raw
        if has_id:
            if "result" in raw or "error" in raw:
                self._handle_response(raw)
                return
            if has_method:  # server-issued request (id + method)
                self._handle_server_request(raw)
                return
        if has_method:  # notification (no id)
            self._handle_notification(raw)

    def _handle_response(self, raw: Dict[str, Any]) -> None:
        rpc_id = raw.get("id")
        if not isinstance(rpc_id, int):
            return
        with self._lock:
            pr = self._pending.pop(rpc_id, None)
        if pr is None:
            return
        if "error" in raw:
            err = raw.get("error") or {}
            pr.q.put((None, "%s: %s (code=%s)" % (
                pr.method, err.get("message", ""), err.get("code", 0))))
        else:
            pr.q.put((raw.get("result"), None))

    def _approval_decision(self, kind: str, params: Any) -> str:
        """Return 'accept' or 'deny' for a codex approval request.

        Consults opts.on_approval_request when set; otherwise auto-accepts
        (the historical daemon behavior).
"""
        tool_input = params if isinstance(params, dict) else {}
        decision = resolve_approval(self.opts, "codex", kind, tool_input,
                                    self.thread_id, self.cfg.logger)
        if decision is not None and decision.decision != "approved":
            self.cfg.logger.info("codex: approval rejected by callback", kind=kind)
            return "deny"
        return "accept"

    def _handle_server_request(self, raw: Dict[str, Any]) -> None:
        rpc_id = raw.get("id")
        method = raw.get("method", "")
        # Auto-approve exec/patch/permission requests in daemon mode, unless a
        # human approval callback is configured and rejects the request.
        if method in ("item/commandExecution/requestApproval", "execCommandApproval"):
            self.respond(rpc_id, {"decision": self._approval_decision(
                "exec", raw.get("params"))})
        elif method in ("item/fileChange/requestApproval", "applyPatchApproval"):
            self.respond(rpc_id, {"decision": self._approval_decision(
                "patch", raw.get("params"))})
        elif method == "item/permissions/requestApproval":
            if self._approval_decision("permissions", raw.get("params")) != "accept":
                self.respond(rpc_id, {"decision": "deny"})
            else:
                self.respond(rpc_id, codex_permissions_approval_response(
                    raw.get("params"), self.cfg.logger))
        elif method == "mcpServer/elicitation/request":
            self.respond(rpc_id, {"action": "accept", "content": None, "_meta": None})
        else:
            msg = "unsupported codex app-server request: %s" % method
            self.cfg.logger.warn("codex: unhandled server request",
                                 method=method, id=rpc_id)
            self.set_turn_error(msg)
            self.respond_error(rpc_id, -32601, msg)

    def _handle_notification(self, raw: Dict[str, Any]) -> None:
        method = raw.get("method", "")
        params = raw.get("params")
        if not isinstance(params, dict):
            params = {}
        # Legacy codex/event notifications.
        if method == "codex/event" or method.startswith("codex/event/"):
            self.notification_protocol = "legacy"
            msg_data = params.get("msg")
            if isinstance(msg_data, dict):
                self._handle_event(msg_data)
            return
        # Raw v2 notifications.
        if self.notification_protocol != "legacy":
            if (self.notification_protocol == "unknown"
                    and (method in ("turn/started", "turn/completed", "thread/started")
                         or method.startswith("item/"))):
                self.notification_protocol = "raw"
            if self.notification_protocol == "raw":
                self._handle_raw_notification(method, params)

    # -- legacy event mapping --

    def _handle_event(self, msg: Dict[str, Any]) -> None:
        msg_type = msg.get("type")
        if msg_type == "task_started":
            self.turn_started = True
            self._emit(Message(type=MessageType.STATUS, status="running",
                               session_id=self.thread_id))
        elif msg_type == "agent_message":
            text = msg.get("message")
            if isinstance(text, str) and text:
                self._emit(Message(type=MessageType.TEXT, content=text))
        elif msg_type == "exec_command_begin":
            self._emit(Message(type=MessageType.TOOL_USE, tool="exec_command",
                               call_id=msg.get("call_id", "") or "",
                               input={"command": msg.get("command", "")}))
        elif msg_type == "exec_command_end":
            self._emit(Message(type=MessageType.TOOL_RESULT, tool="exec_command",
                               call_id=msg.get("call_id", "") or "",
                               output=msg.get("output", "") or ""))
        elif msg_type == "patch_apply_begin":
            self._emit(Message(type=MessageType.TOOL_USE, tool="patch_apply",
                               call_id=msg.get("call_id", "") or ""))
        elif msg_type == "patch_apply_end":
            self._emit(Message(type=MessageType.TOOL_RESULT, tool="patch_apply",
                               call_id=msg.get("call_id", "") or ""))
        elif msg_type == "task_complete":
            self._extract_usage_from_map(msg)
            self.on_turn_done(False)
        elif msg_type == "turn_aborted":
            self.on_turn_done(True)

    # -- raw v2 notification mapping --

    def _handle_raw_notification(self, method: str, params: Dict[str, Any]) -> None:
        # Ignore notifications from threads other than the one we track (codex
        # multiplexes subagent threads on the same stdio pipe).
        thread_id = params.get("threadId")
        if (isinstance(thread_id, str) and self.thread_id
                and thread_id != self.thread_id):
            return

        if method == "turn/started":
            self.turn_started = True
            turn_id = extract_nested_string(params, "turn", "id")
            if turn_id:
                self.turn_id = turn_id
            self._emit(Message(type=MessageType.STATUS, status="running",
                               session_id=self.thread_id))
        elif method == "turn/completed":
            turn_id = extract_nested_string(params, "turn", "id")
            status = extract_nested_string(params, "turn", "status")
            self.cfg.logger.info("codex turn/completed received",
                                 thread_id=params.get("threadId", ""),
                                 turn_id=turn_id, status=status)
            aborted = status in ("cancelled", "canceled", "aborted", "interrupted")
            if status == "failed":
                err_msg = extract_nested_string(params, "turn", "error", "message")
                self.set_turn_error(err_msg or "codex turn failed")
            if turn_id:
                if self._completed_turn_ids.get(turn_id):
                    return
                self._completed_turn_ids[turn_id] = True
            turn = params.get("turn")
            if isinstance(turn, dict):
                self._extract_usage_from_map(turn)
            self.on_turn_done(aborted)
        elif method == "error":
            # willRetry notifications are transient reconnects; only terminal
            # errors are captured.
            will_retry = bool(params.get("willRetry"))
            err_msg = extract_nested_string(params, "error", "message")
            if not err_msg:
                err_msg = extract_nested_string(params, "message")
            if err_msg:
                self.cfg.logger.warn("codex error notification",
                                     message=err_msg, will_retry=will_retry)
                self.on_semantic_activity("error:retry" if will_retry else "error:terminal")
                if not will_retry:
                    self.set_turn_error(err_msg)
                    self.on_turn_done(False)
        elif method == "thread/status/changed":
            status_type = extract_nested_string(params, "status", "type")
            if status_type == "idle" and self.turn_started:
                self.on_turn_done(False)
        elif method.startswith("item/"):
            self._handle_item_notification(method, params)

    def _handle_item_notification(self, method: str, params: Dict[str, Any]) -> None:
        item = params.get("item")
        item = item if isinstance(item, dict) else None
        item_type = (item or {}).get("type", "") if item else ""
        item_id = (item or {}).get("id", "") if item else ""
        if method.startswith("item/"):
            self.on_semantic_activity(_describe_codex_item_progress_activity(
                method, item_type or "", item_id or ""))
        if item is None:
            return

        if method == "item/started" and item_type == "commandExecution":
            self._emit(Message(type=MessageType.TOOL_USE, tool="exec_command",
                               call_id=item_id or "",
                               input={"command": item.get("command", "")}))
        elif method == "item/completed" and item_type == "commandExecution":
            self._emit(Message(type=MessageType.TOOL_RESULT, tool="exec_command",
                               call_id=item_id or "",
                               output=item.get("aggregatedOutput", "") or ""))
        elif method == "item/started" and item_type == "fileChange":
            self._emit(Message(type=MessageType.TOOL_USE, tool="patch_apply",
                               call_id=item_id or ""))
        elif method == "item/completed" and item_type == "fileChange":
            self._emit(Message(type=MessageType.TOOL_RESULT, tool="patch_apply",
                               call_id=item_id or ""))
        elif method == "item/completed" and item_type == "agentMessage":
            text = item.get("text", "")
            if isinstance(text, str) and text:
                self._emit(Message(type=MessageType.TEXT, content=text))
            if item.get("phase") == "final_answer" and self.turn_started:
                self.on_turn_done(False)

    def _emit(self, msg: Message) -> None:
        _log_codex_agent_message(self.cfg.logger, msg)
        self.on_message(msg)

    # -- usage --

    def _extract_usage_from_map(self, data: Dict[str, Any]) -> None:
        usage_map = None
        for key in ("usage", "token_usage", "tokens"):
            v = data.get(key)
            if isinstance(v, dict):
                usage_map = v
                break
        if usage_map is None:
            return
        with self._usage_lock:
            input_tokens = _codex_int64(usage_map, "input_tokens", "input", "prompt_tokens")
            cache_read = _codex_int64(usage_map, "cached_input_tokens",
                                      "cache_read_tokens", "cache_read_input_tokens")
            self.usage.input_tokens += _codex_uncached_input_tokens(input_tokens, cache_read)
            self.usage.output_tokens += _codex_int64(
                usage_map, "output_tokens", "output", "completion_tokens")
            self.usage.cache_read_tokens += cache_read
            self.usage.cache_write_tokens += _codex_int64(
                usage_map, "cache_write_tokens", "cache_creation_input_tokens")

    # -- thread start / resume --

    def start_or_resume_thread(self, opts: ExecOptions,
                               logger: Logger) -> Tuple[str, bool, Optional[str]]:
        prior = opts.resume_session_id
        if prior:
            resume_params = {
                "threadId": prior, "cwd": opts.cwd,
                "model": _nil_if_empty(opts.model),
                "developerInstructions": _nil_if_empty(opts.system_prompt),
            }
            apply_codex_reasoning_effort(resume_params, opts.thinking_level)
            result, err = self.request("thread/resume", resume_params)
            if err is None:
                tid = extract_thread_id(result)
                if tid:
                    return tid, True, None
                logger.warn("codex thread/resume returned no thread ID; falling "
                            "back to thread/start", prior_thread_id=prior)
            else:
                if _is_codex_transport_error(err):
                    logger.warn("codex thread/resume failed due to transport "
                                "error; not falling back to thread/start",
                                prior_thread_id=prior, error=err)
                    return "", False, "codex thread/resume failed: %s" % err
                logger.warn("codex thread/resume failed; falling back to "
                            "thread/start", prior_thread_id=prior, error=err)

        start_params = {
            "model": _nil_if_empty(opts.model),
            "modelProvider": None, "profile": None, "cwd": opts.cwd,
            "approvalPolicy": None, "sandbox": None, "config": None,
            "baseInstructions": None,
            "developerInstructions": _nil_if_empty(opts.system_prompt),
            "compactPrompt": None, "includeApplyPatchTool": None,
            "experimentalRawEvents": False, "persistExtendedHistory": True,
        }
        apply_codex_reasoning_effort(start_params, opts.thinking_level)
        result, err = self.request("thread/start", start_params)
        if err is not None:
            return "", False, "codex thread/start failed: %s" % err
        tid = extract_thread_id(result)
        if not tid:
            return "", False, "codex thread/start returned no thread ID"
        self._try_set_thread_name(tid, opts.thread_name, logger)
        return tid, False, None

    def _try_set_thread_name(self, thread_id: str, name: str, logger: Logger) -> None:
        name = (name or "").strip()
        if not name:
            return
        _result, err = self.request("thread/name/set",
                                    {"threadId": thread_id, "name": name})
        if err is not None:
            logger.warn("codex thread/name/set failed; continuing without "
                        "provider-native thread title",
                        thread_id=thread_id, error=err)


def _is_codex_transport_error(err: str) -> bool:
    if not err:
        return False
    if _ERR_CODEX_PROCESS_EXITED in err:
        return True
    return err.startswith("write ")


def codex_permissions_approval_response(params: Any, logger: Logger) -> Dict[str, Any]:
    """Auto-grant reply for item/permissions/requestApproval (daemon mode).

    Echoes back the requested network / fileSystem profile, turn-scoped.
    """
    permissions: Dict[str, Any] = {}
    if isinstance(params, dict):
        p = params.get("permissions")
        if isinstance(p, dict):
            permissions = p
    granted: Dict[str, Any] = {}
    dropped: List[str] = []
    for key, value in permissions.items():
        if key in ("network", "fileSystem"):
            if value is not None:
                granted[key] = value
        else:
            dropped.append(key)
    if dropped:
        logger.warn("codex: dropping unrecognized permission keys from approval "
                    "request; add explicit handling if the app-server protocol "
                    "expanded", keys=sorted(dropped))
    return {"permissions": granted, "scope": "turn"}


def _log_codex_agent_message(logger: Logger, msg: Message) -> None:
    logger.info("codex agent message received",
                type=msg.type.value, tool=msg.tool, call_id=msg.call_id,
                status=msg.status, content_len=len(msg.content),
                output_len=len(msg.output))
    if msg.type == MessageType.TOOL_RESULT:
        logger.info("codex tool_result observed", tool=msg.tool,
                    call_id=msg.call_id, output_len=len(msg.output))


# -- Codex session-log usage scanner (JSON-RPC usage fallback) ---------


def codex_session_root() -> str:
    codex_home = os.environ.get("CODEX_HOME")
    if codex_home:
        d = os.path.join(codex_home, "sessions")
        if os.path.isdir(d):
            return d
    home = os.path.expanduser("~")
    if home:
        d = os.path.join(home, ".codex", "sessions")
        if os.path.isdir(d):
            return d
    return ""


def _parse_codex_session_file(path: str) -> Optional[Tuple[TokenUsage, str]]:
    found = False
    usage = TokenUsage()
    model = ""
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            for line in f:
                if "token_count" not in line and "turn_context" not in line:
                    continue
                try:
                    evt = json.loads(line)
                except Exception:
                    continue
                payload = evt.get("payload") if isinstance(evt, dict) else None
                if not isinstance(payload, dict):
                    continue
                if evt.get("type") == "turn_context" and payload.get("model"):
                    model = payload["model"]
                    continue
                if payload.get("type") == "token_count":
                    info = payload.get("info")
                    if not isinstance(info, dict):
                        continue
                    tu = info.get("total_token_usage") or info.get("last_token_usage")
                    if not isinstance(tu, dict):
                        continue
                    cached = tu.get("cached_input_tokens", 0) or tu.get("cache_read_input_tokens", 0)
                    usage = TokenUsage(
                        input_tokens=_codex_uncached_input_tokens(
                            int(tu.get("input_tokens", 0)), int(cached)),
                        output_tokens=int(tu.get("output_tokens", 0))
                        + int(tu.get("reasoning_output_tokens", 0)),
                        cache_read_tokens=int(cached),
                    )
                    if info.get("model"):
                        model = info["model"]
                    found = True
    except Exception:
        return None
    if not found:
        return None
    return usage, model


def scan_codex_session_usage(start_time: float) -> Optional[Tuple[TokenUsage, str]]:
    """Scan Codex session JSONL files modified after start_time for usage.

    Codex writes token_count events to
    ``$CODEX_HOME|~/.codex/sessions/YYYY/MM/DD/*.jsonl``.
    """
    import glob as _glob
    root = codex_session_root()
    if not root:
        return None
    lt = time.localtime(start_time)
    date_dir = os.path.join(root, "%04d" % lt.tm_year,
                            "%02d" % lt.tm_mon, "%02d" % lt.tm_mday)
    files = _glob.glob(os.path.join(date_dir, "*.jsonl"))
    if not files:
        return None
    result: Optional[Tuple[TokenUsage, str]] = None
    for f in files:
        try:
            if os.path.getmtime(f) < start_time:
                continue
        except OSError:
            continue
        parsed = _parse_codex_session_file(f)
        if parsed is not None:
            result = parsed  # last matching file wins
    if result is None:
        return None
    if result[0].input_tokens == 0 and result[0].output_tokens == 0:
        return None
    return result


# -- Backend -----------------------------------------------------------


class CodexBackend:
    """Backend implementation for the ``codex app-server`` JSON-RPC protocol."""

    def __init__(self, cfg: Config) -> None:
        self.cfg = cfg

    def execute(self, prompt: str, opts: ExecOptions,
                cancel: Optional[threading.Event] = None) -> Session:
        exec_path = self.cfg.executable_path or "codex"
        if shutil.which(exec_path) is None and not os.path.isabs(exec_path):
            raise FileNotFoundError("codex executable not found at %r" % exec_path)

        env = build_env(self.cfg.env)

        # Materialise the agent's managed MCP config into the per-task
        # $CODEX_HOME/config.toml (secrets stay out of argv/logs). Fail closed.
        codex_home = (self.cfg.env.get("CODEX_HOME") or "").strip()
        if codex_home:
            try:
                ensure_codex_mcp_config(os.path.join(codex_home, "config.toml"),
                                        opts.mcp_config, self.cfg.logger)
            except Exception as exc:  # noqa: BLE001
                raise RuntimeError("apply codex mcp_config: %s" % exc)
        elif has_managed_codex_mcp_config(opts.mcp_config):
            raise RuntimeError(
                "codex: mcp_config is set but CODEX_HOME env var is not "
                "configured; cannot apply managed MCP")

        args = build_codex_args(opts, self.cfg.logger)
        argv = [exec_path] + args
        self.cfg.logger.info("agent command", exec=exec_path, args=args)

        proc = subprocess.Popen(
            argv, cwd=opts.cwd or None, env=env,
            stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            bufsize=0, **popen_platform_kwargs())
        self.cfg.logger.info("codex started app-server", pid=proc.pid, cwd=opts.cwd)

        session = Session(capture_transcript=bool(getattr(opts, "capture_transcript", False)))
        threading.Thread(
            target=self._run, args=(proc, prompt, opts, cancel, session, env),
            daemon=True).start()
        return session

    def _run(self, proc: "subprocess.Popen", prompt: str, opts: ExecOptions,
             cancel: Optional[threading.Event], session: Session,
             env: Dict[str, str]) -> None:
        import queue as _queue
        logger = self.cfg.logger
        exec_path = self.cfg.executable_path or "codex"

        stderr_tail = StderrTail(
            max_bytes=CODEX_STDERR_TAIL_BYTES,
            inner=lambda b: logger.debug(
                "[codex:stderr] %s" % b.decode("utf-8", "replace").rstrip()))

        def _drain_stderr() -> None:
            if proc.stderr is None:
                return
            for chunk in iter(lambda: proc.stderr.readline(), b""):
                stderr_tail.write(chunk)

        threading.Thread(target=_drain_stderr, daemon=True).start()

        semantic_timeout = opts.semantic_inactivity_timeout
        if semantic_timeout == 0:
            semantic_timeout = DEFAULT_CODEX_SEMANTIC_INACTIVITY_TIMEOUT

        # lifecycle_q multiplexes the events the Go loop selected over.
        lifecycle_q: "_queue.Queue[Tuple[str, Any]]" = _queue.Queue(maxsize=512)
        output_parts: List[str] = []
        output_lock = threading.Lock()

        def on_message(msg: Message) -> None:
            if msg.type == MessageType.TEXT:
                with output_lock:
                    output_parts.append(msg.content)
            session._emit(msg)
            _try_put(lifecycle_q, ("activity", describe_codex_semantic_activity(msg)))

        def on_semantic_activity(description: str) -> None:
            logger.debug("codex semantic activity observed", activity=description)
            _try_put(lifecycle_q, ("activity", description))

        def on_turn_done(aborted: bool) -> None:
            _try_put(lifecycle_q, ("turn_done", aborted))

        client = CodexClient(self.cfg, proc.stdin, on_message,
                             on_semantic_activity, on_turn_done, opts)

        # -- reader thread --
        reader_done = threading.Event()

        def _reader() -> None:
            try:
                assert proc.stdout is not None
                for raw in proc.stdout:
                    line = raw.decode("utf-8", "replace").strip() if isinstance(raw, bytes) else raw.strip()
                    if not line:
                        continue
                    try:
                        client.handle_line(line)
                    except Exception as exc:  # noqa: BLE001
                        logger.warn("codex: line handler error", error=str(exc))
            except Exception as exc:  # noqa: BLE001
                client.mark_process_exited("%s: %s" % (_ERR_CODEX_PROCESS_EXITED, exc))
                reader_done.set()
                _try_put(lifecycle_q, ("process_exited", None))
                return
            client.mark_process_exited(_ERR_CODEX_PROCESS_EXITED)
            reader_done.set()
            _try_put(lifecycle_q, ("process_exited", None))

        reader_thread = threading.Thread(target=_reader, daemon=True)
        reader_thread.start()

        # -- watchdog: wall-clock timeout + cancel event --
        start_time = time.time()
        start_mono = time.monotonic()
        deadline = start_mono + opts.timeout if opts.timeout and opts.timeout > 0 else None
        watchdog_stop = threading.Event()
        killed = {"reason": None}  # "timeout" | "cancelled"

        def _watchdog() -> None:
            while not watchdog_stop.wait(0.1):
                if proc.poll() is not None:
                    return
                if deadline is not None and time.monotonic() > deadline:
                    killed["reason"] = "timeout"
                    signal_process_group(proc, signal.SIGKILL)
                    _try_put(lifecycle_q, ("runctx_done", "timeout"))
                    return
                if cancel is not None and cancel.is_set():
                    killed["reason"] = "cancelled"
                    signal_process_group(proc, signal.SIGKILL)
                    _try_put(lifecycle_q, ("runctx_done", "cancelled"))
                    return

        threading.Thread(target=_watchdog, daemon=True).start()

        # -- graceful drain / wait (two-phase Go drainAndWait, simplified) --
        wait_lock = threading.Lock()
        wait_done = {"v": False}

        def drain_and_wait() -> None:
            with wait_lock:
                if wait_done["v"]:
                    return
                wait_done["v"] = True
            try:
                if proc.stdin is not None:
                    proc.stdin.close()
            except Exception:
                pass
            grace = CODEX_GRACEFUL_SHUTDOWN_TIMEOUT
            # Phase 1: let the reader finish (codex closes stdout on clean exit,
            # flushing OTEL telemetry) before reaping the process.
            reader_thread.join(grace)
            if reader_thread.is_alive():
                logger.warn("codex did not close stdout after stdin EOF; forcing "
                            "shutdown", pid=proc.pid, grace=grace)
                signal_process_group(proc, signal.SIGKILL)
                reader_thread.join(grace)
            # Phase 2: bound the process reap.
            try:
                proc.wait(timeout=grace)
            except Exception:
                logger.warn("codex process still alive after reader exited; "
                            "forcing shutdown", pid=proc.pid, grace=grace)
                signal_process_group(proc, signal.SIGKILL)
                try:
                    proc.wait(timeout=grace)
                except Exception:
                    pass

        final_status = "completed"
        final_error = ""
        process_exit_err: Optional[str] = None
        timeout_diag = _TimeoutDiagnostic()
        thread_id = ""

        def finalize(status: str, error: str) -> None:
            nonlocal final_status, final_error
            final_status = status
            final_error = error

        try:
            # 1. initialize handshake
            _res, err = client.request("initialize", {
                "clientInfo": {"name": "multica-agent-sdk",
                               "title": "Multica Agent SDK", "version": "0.2.0"},
                "capabilities": {"experimentalApi": True},
            })
            if err is not None:
                drain_and_wait()
                finalize("failed", with_agent_stderr(
                    "codex initialize failed: %s" % err, "codex", stderr_tail.tail()))
                self._emit_result(session, final_status, output_parts, output_lock,
                                  final_error, thread_id, start_mono, client, opts, env)
                return
            client.notify("initialized")

            # 2. start or resume the thread
            thread_id, resumed, err = client.start_or_resume_thread(opts, logger)
            if err is not None:
                drain_and_wait()
                finalize("failed",
                         with_agent_stderr(err, "codex", stderr_tail.tail()))
                self._emit_result(session, final_status, output_parts, output_lock,
                                  final_error, thread_id, start_mono, client, opts, env)
                return
            client.thread_id = thread_id
            logger.info("codex thread resumed" if resumed else "codex thread started",
                        thread_id=thread_id)

            # 3. send the turn
            turn_params: Dict[str, Any] = {
                "threadId": thread_id,
                "input": [{"type": "text", "text": prompt}],
            }
            apply_codex_reasoning_effort(turn_params, opts.thinking_level)

            def finish_turn(aborted: bool) -> None:
                if aborted:
                    err_msg = client.get_turn_error()
                    finalize("aborted", err_msg if err_msg else "turn was aborted")
                else:
                    err_msg = client.get_turn_error()
                    if err_msg:
                        finalize("failed", err_msg)

            _res, err = client.request("turn/start", turn_params)
            waiting = True
            if err is not None:
                # Peek for an already-queued turn_done before failing.
                aborted_evt = _drain_for_turn_done(lifecycle_q)
                if aborted_evt is not None:
                    finish_turn(aborted_evt)
                    waiting = False
                else:
                    drain_and_wait()
                    finalize("failed", with_agent_stderr(
                        "codex turn/start failed: %s" % err, "codex", stderr_tail.tail()))
                    self._emit_result(session, final_status, output_parts, output_lock,
                                      final_error, thread_id, start_mono, client, opts, env)
                    return

            # 4. event loop with the two inactivity timers.
            now = time.monotonic()
            last_activity_desc = "turn/start"
            semantic_deadline = now + semantic_timeout
            first_turn_timeout = codex_first_turn_no_progress_timeout(semantic_timeout)
            first_turn_started = False
            first_turn_progress_observed = False
            first_turn_deadline: Optional[float] = None

            while waiting:
                now = time.monotonic()
                deadlines = [semantic_deadline]
                if first_turn_deadline is not None:
                    deadlines.append(first_turn_deadline)
                wait_for = max(0.0, min(deadlines) - now)
                try:
                    evt = lifecycle_q.get(timeout=wait_for)
                except _queue.Empty:
                    evt = None
                now = time.monotonic()

                if evt is None:  # a timer expired
                    if first_turn_deadline is not None and now >= first_turn_deadline:
                        waiting = False
                        finalize("timeout", "")
                        timeout_diag.kind = _TIMEOUT_FIRST_TURN_NO_PROGRESS
                        timeout_diag.timeout = first_turn_timeout
                        timeout_diag.last_activity = last_activity_desc
                        timeout_diag.thread_id = thread_id
                        timeout_diag.turn_id = client.turn_id
                        timeout_diag.model = opts.model
                        logger.warn(CODEX_FIRST_TURN_NO_PROGRESS_MARKER,
                                    pid=proc.pid, thread_id=thread_id,
                                    turn_id=client.turn_id, timeout=first_turn_timeout,
                                    last_activity=last_activity_desc)
                    elif now >= semantic_deadline:
                        waiting = False
                        finalize("timeout", "")
                        timeout_diag.kind = _TIMEOUT_SEMANTIC_INACTIVITY
                        timeout_diag.timeout = semantic_timeout
                        timeout_diag.last_activity = last_activity_desc
                        timeout_diag.thread_id = thread_id
                        timeout_diag.turn_id = client.turn_id
                        timeout_diag.model = opts.model
                        logger.warn(CODEX_SEMANTIC_INACTIVITY_MARKER,
                                    pid=proc.pid, thread_id=thread_id,
                                    turn_id=client.turn_id, timeout=semantic_timeout,
                                    last_activity=last_activity_desc)
                    continue

                kind, payload = evt
                if kind == "turn_done":
                    finish_turn(bool(payload))
                    waiting = False
                elif kind == "activity":
                    activity = payload or ""
                    last_activity_desc = activity
                    semantic_deadline = time.monotonic() + semantic_timeout
                    if activity == "status:running" and not first_turn_started:
                        first_turn_started = True
                        first_turn_deadline = time.monotonic() + first_turn_timeout
                    elif (first_turn_started and not first_turn_progress_observed
                          and is_codex_first_turn_progress_activity(activity)):
                        first_turn_progress_observed = True
                        first_turn_deadline = None
                elif kind == "runctx_done":
                    waiting = False
                    if payload == "timeout":
                        finalize("timeout", "codex timed out after %ss" % opts.timeout)
                    else:
                        finalize("aborted", "execution cancelled")
                elif kind == "process_exited":
                    aborted_evt = _drain_for_turn_done(lifecycle_q)
                    if aborted_evt is not None:
                        finish_turn(aborted_evt)
                        waiting = False
                    elif killed["reason"] == "timeout":
                        waiting = False
                        finalize("timeout", "codex timed out after %ss" % opts.timeout)
                    elif killed["reason"] == "cancelled":
                        waiting = False
                        finalize("aborted", "execution cancelled")
                    else:
                        waiting = False
                        process_exit_err = client.get_process_err() or _ERR_CODEX_PROCESS_EXITED
                        finalize("failed", process_exit_err)

            duration_ms = int((time.monotonic() - start_mono) * 1000)
            logger.info("codex finished", pid=proc.pid,
                        status=final_status, duration_ms=duration_ms)

            drain_and_wait()

            if process_exit_err is not None:
                final_error = with_agent_stderr(process_exit_err, "codex",
                                                stderr_tail.tail())
            if timeout_diag.kind != _TIMEOUT_NONE:
                timeout_diag.codex_version = detect_codex_version_for_diagnostics(
                    exec_path, env, logger)
                final_error = build_codex_timeout_diagnostic_error(
                    timeout_diag, stderr_tail.tail())

            self._emit_result(session, final_status, output_parts, output_lock,
                              final_error, thread_id, start_mono, client, opts, env)
        except Exception as exc:  # noqa: BLE001
            logger.error("codex lifecycle crashed", error=str(exc))
            drain_and_wait()
            self._emit_result(session, "failed", output_parts, output_lock,
                              "codex internal error: %s" % exc, thread_id,
                              start_mono, client, opts, env, start_time=start_time)
        finally:
            watchdog_stop.set()

    def _emit_result(self, session: Session, status: str, output_parts: List[str],
                     output_lock: threading.Lock, error: str, thread_id: str,
                     start_mono: float, client: CodexClient, opts: ExecOptions,
                     env: Dict[str, str], start_time: Optional[float] = None) -> None:
        duration_ms = int((time.monotonic() - start_mono) * 1000)
        with output_lock:
            final_output = "".join(output_parts)

        # Usage: prefer JSON-RPC accumulation; fall back to session JSONL logs.
        with client._usage_lock:
            u = TokenUsage(client.usage.input_tokens, client.usage.output_tokens,
                           client.usage.cache_read_tokens, client.usage.cache_write_tokens)
        model = opts.model
        if u.input_tokens == 0 and u.output_tokens == 0:
            scanned = scan_codex_session_usage(start_time or time.time()
                                               if start_time else _mono_to_wall(start_mono))
            if scanned is not None:
                u = scanned[0]
                if scanned[1] and not model:
                    model = scanned[1]

        usage_map: Dict[str, TokenUsage] = {}
        if (u.input_tokens > 0 or u.output_tokens > 0
                or u.cache_read_tokens > 0 or u.cache_write_tokens > 0):
            usage_map = {model or "unknown": u}

        session._set_result(Result(
            status=status, output=final_output, error=error,
            duration_ms=duration_ms, session_id=thread_id, usage=usage_map))
        session._close_messages()


def _mono_to_wall(start_mono: float) -> float:
    """Approximate the wall-clock start time from a monotonic start reading."""
    return time.time() - (time.monotonic() - start_mono)


def _try_put(q: Any, item: Any) -> None:
    try:
        q.put_nowait(item)
    except Exception:
        pass


def _drain_for_turn_done(q: Any) -> Optional[bool]:
    """Non-blocking peek: return the aborted flag if a turn_done is queued."""
    import queue as _queue
    aborted: Optional[bool] = None
    pending: List[Tuple[str, Any]] = []
    while True:
        try:
            evt = q.get_nowait()
        except _queue.Empty:
            break
        if evt[0] == "turn_done" and aborted is None:
            aborted = bool(evt[1])
        else:
            pending.append(evt)
    for evt in pending:  # re-queue non-turn_done events
        _try_put(q, evt)
    return aborted
