"""Codex backend (port of codex.go).

The daemon spawns ``codex app-server --listen stdio://`` and speaks JSON-RPC
2.0 over the child's stdin/stdout. This is the only backend that does *not*
use :class:`StreamingRunner`; the line protocol is a bidirectional RPC where
the daemon issues requests (initialize / thread.start / turn.start), answers
server-issued approval requests, and consumes streamed notifications.

The Go original leaned on goroutines + ``select`` over several channels (a
turn-done channel, a semantic-activity channel, wall-clock context
cancellation, and process-exit). Here the same shape is expressed with:

  * a background *reader* thread that decodes each stdout line and dispatches
    it (responses unblock the corresponding ``request``; server requests are
    auto-approved; notifications map to unified :class:`Message` events);
  * a *lifecycle* thread that runs the handshake, starts/resumes the thread,
    fires the turn, then blocks on a single ``lifecycle_q`` queue while
    computing the two inactivity timers itself (``queue.get`` with a deadline
    replaces Go's ``time.Timer`` + ``select``);
  * a *watchdog* thread for the wall-clock ``opts.timeout`` and the ``cancel``
    event; it signal-kills the whole process group.

Per-request correlation, the initialize handshake, turn dispatch, streamed
event mapping, approval auto-accept, token-usage accumulation (JSON-RPC plus a
session-JSONL fallback), session-id capture and final Result computation are
all reproduced. See the "notable deviations" note at the bottom of the module.
"""

